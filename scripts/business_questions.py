"""
scripts/business_questions.py
-----------------------------
Runs the six business questions against the ETL tables and the ELT marts of
include/warehouse_ashish_kamat.duckdb and writes:

  docs/business_questions.md                 SQL + results (both pipelines)
  docs/evidence/business_questions/*.csv     full result sets

Read-only. Only masked customer identifiers are ever selected.
"""

from __future__ import annotations

from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
OUT_MD = ROOT / "docs" / "business_questions.md"
OUT_CSV = ROOT / "docs" / "evidence" / "business_questions"

QUESTIONS = [
    ("Q1", "Daily net revenue by zone and by store (DELIVERED only, after discount)",
     "SELECT order_date, zone, store_id, store_name, delivered_orders, net_revenue\nFROM {t}\nORDER BY order_date, zone, store_id;",
     {"etl": "etl_daily_zone_revenue", "elt": "mart_daily_store_kpis"},
     # summaries shown in the markdown (the full daily table is in the CSV)
     ["SELECT zone, sum(delivered_orders) AS delivered_orders, sum(net_revenue) AS net_revenue\nFROM {t} WHERE order_date BETWEEN DATE '2026-09-01' AND DATE '2026-09-30'\nGROUP BY zone ORDER BY net_revenue DESC;",
      "SELECT store_id, store_name, zone, sum(delivered_orders) AS delivered_orders, sum(net_revenue) AS net_revenue\nFROM {t} WHERE order_date BETWEEN DATE '2026-09-01' AND DATE '2026-09-30'\nGROUP BY ALL ORDER BY net_revenue DESC;",
      "SELECT order_date, zone, store_id, delivered_orders, net_revenue\nFROM {t} WHERE order_date = DATE '2026-09-30' ORDER BY zone, store_id;"]),
    ("Q2", "Revenue and gross margin by product category (margin = revenue - quantity x cost_price)",
     "SELECT category, delivered_orders, units, net_revenue, cost_amount, gross_margin, margin_pct, orders_without_cost\nFROM {t}\nORDER BY net_revenue DESC;",
     {"etl": "etl_category_margin", "elt": "mart_category_margin"}, None),
    ("Q3", "Average delivery time per store and % of delivered orders within 15 minutes",
     "SELECT store_id, store_name, zone, delivered_orders, avg_delivery_minutes, pct_within_15_min\nFROM {t}\nORDER BY store_id;",
     {"etl": "etl_delivery_sla", "elt": "mart_delivery_sla"}, None),
    ("Q4", "Revenue by payment mode, and the amount that does not reconcile with the payment gateway",
     "SELECT payment_mode, delivered_orders, net_revenue, mismatches, unreconciled_amount\nFROM {t}\nORDER BY net_revenue DESC;",
     {"etl": "etl_payment_mode_revenue", "elt": "mart_payment_mode_revenue"},
     ["SELECT reason, count(*) AS mismatches, sum(unreconciled_amount) AS unreconciled_amount\nFROM {r} GROUP BY reason ORDER BY reason;",
      "SELECT sum(unreconciled_amount) AS total_unreconciled_amount, count(*) AS mismatch_rows FROM {r};"]),
    ("Q5", "Top 10 customers by spend, with loyalty tier (masked identifiers only)",
     "SELECT spend_rank, customer_id, full_name_masked, email_masked, phone_masked, loyalty_tier, delivered_orders, net_revenue\nFROM {t}\nORDER BY spend_rank;",
     {"etl": "etl_top_customers", "elt": "mart_top_customers"}, None),
    ("Q6", "Rows rejected today, by file and by reason",
     None, {"etl": "etl_rejected_rows", "elt": "mart_rejected_rows"}, None),
]
RECON = {"etl": "etl_payment_reconciliation", "elt": "mart_payment_reconciliation"}
Q6_SQL = {
    "etl": "SELECT source_file, check_name, rows_rejected\nFROM etl_rejected_rows\nWHERE run_id = (SELECT run_id FROM pipeline_runs WHERE dag_id = 'nammamart_etl_ashish_kamat'\n                AND status <> 'FAILED' ORDER BY end_time DESC LIMIT 1)\nORDER BY source_file, rows_rejected DESC, check_name;",
    "elt": "SELECT source_file, check_name, rows_rejected\nFROM mart_rejected_rows\nORDER BY source_file, rows_rejected DESC, check_name;",
}


def md_table(df) -> str:
    return df.to_markdown(index=False, floatfmt=".2f")


def main() -> None:
    con = duckdb.connect(str(ROOT / "include" / "warehouse_ashish_kamat.duckdb"), read_only=True)
    OUT_CSV.mkdir(parents=True, exist_ok=True)
    runs = con.execute("SELECT dag_id, run_id, end_time, status FROM pipeline_runs "
                       "WHERE status <> 'FAILED' ORDER BY end_time DESC").df()
    lines = ["# Business questions: SQL and results from both pipelines\n",
             "Generated by `scripts/business_questions.py` (read-only) from `include/warehouse_ashish_kamat.duckdb`.",
             "Results reflect the warehouse state after the latest successful run of each DAG:\n",
             md_table(runs.groupby("dag_id").head(1)), "",
             "State includes `orders_2026-10-01_increment.csv` (10 September orders corrected DELIVERED -> RETURNED, "
             "150 new orders dated 1 Oct 2026). Revenue = DELIVERED orders only, after discount. "
             "ETL tables and ELT marts are produced by independent code (pandas vs SQL); each question below shows "
             "both and states whether they match row for row.\n"]
    for qid, title, sql, tables, extras in QUESTIONS:
        lines.append(f"## {qid}. {title}\n")
        results = {}
        for p in ("etl", "elt"):
            q = Q6_SQL[p] if qid == "Q6" else sql.format(t=tables[p])
            df = con.execute(q).df()
            results[p] = df
            df.to_csv(OUT_CSV / f"{qid}_{p}.csv", index=False)
            lines.append(f"**{p.upper()}** (`{tables[p]}`)\n\n```sql\n{q}\n```\n")
        same = results["etl"].astype(str).equals(results["elt"].astype(str))
        lines.append(f"ETL vs ELT: **{'identical' if same else 'DIFFERENT'}** "
                     f"({len(results['etl'])} vs {len(results['elt'])} rows). "
                     f"Full results: `docs/evidence/business_questions/{qid}_etl.csv`, `{qid}_elt.csv`.\n")
        if qid == "Q1":
            for x in extras:
                df_e = con.execute(x.format(t=tables["etl"])).df()
                df_l = con.execute(x.format(t=tables["elt"])).df()
                lines.append(f"```sql\n{x.format(t=tables['etl'])}\n```\n")
                lines.append(md_table(df_e) + "\n")
                lines.append(f"ELT (`{tables['elt']}`) gives the same result: **{df_e.astype(str).equals(df_l.astype(str))}**\n")
        else:
            lines.append(md_table(results["etl"]) + "\n")
        if qid == "Q4":
            for x in extras:
                df_e = con.execute(x.format(r=RECON["etl"])).df()
                df_l = con.execute(x.format(r=RECON["elt"])).df()
                lines.append(f"```sql\n{x.format(r=RECON['etl'])}\n```\n")
                lines.append(md_table(df_e) + "\n")
                lines.append(f"ELT (`{RECON['elt']}`) gives the same result: **{df_e.astype(str).equals(df_l.astype(str))}**\n")
    OUT_MD.write_text("\n".join(lines))
    print(f"wrote {OUT_MD}")


if __name__ == "__main__":
    main()
